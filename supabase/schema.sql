-- Run this in Supabase SQL Editor if you want RSVP responses shared across devices.
create table if not exists public.rsvps (
  id bigint generated by default as identity primary key,
  guest_name text not null,
  guest_key text not null unique,
  response text not null check (response in ('yes', 'no')),
  created_at timestamptz not null default now()
);

alter table public.rsvps enable row level security;

-- Guests can submit/update only their own RSVP using a guest_key.
-- For a small invitation website this policy allows insert/update via anon key.
-- Do not store sensitive information in this table.
create policy "Guests can add RSVP"
on public.rsvps for insert
to anon
with check (guest_key <> '' and response in ('yes', 'no'));

create policy "Guests can update RSVP"
on public.rsvps for update
to anon
using (guest_key <> '')
with check (guest_key <> '' and response in ('yes', 'no'));

